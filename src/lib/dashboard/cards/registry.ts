/** Platform-owned. Adding a card is a reviewed code change (DSH-D10). */
export const DASHBOARD_CARDS: readonly DashboardCardDefinition[] = Object.freeze(
  definitions.map((definition) => Object.freeze(definition)),
);

export function getDashboardCard(id: string): DashboardCardDefinition | null {
  return DASHBOARD_CARDS.find((card) => card.id === id) ?? null;
}

import ExcelJS from "exceljs";

import type { ComplianceReport } from "./types";

export async function renderComplianceWorkbook(report: ComplianceReport): Promise<Buffer> {
  const book = new ExcelJS.Workbook();
  book.creator = "LTC Manager";
  const summary = book.addWorksheet("Summary");
  summary.addRows([
    ["Facility", report.metadata.facilityName],
    ["Department", report.metadata.departmentName],
    ["Template", report.metadata.templateName],
    ["Template key", report.metadata.templateStableKey],
    ["From", report.metadata.fromDateKey],
    ["To", report.metadata.toDateKey],
    ["Timezone", report.metadata.timezone],
    ["Generated", report.metadata.generatedAt],
    ["Generated by", report.metadata.generatedBy],
    ["Filters", report.metadata.filters.join("; ")],
    [],
    ["Expected", report.summary.expected],
    ["Completed", report.summary.completed],
    ["Missed", report.summary.missed],
    ["Not yet due", report.summary.notYetDue],
    ["Needs setup", report.summary.needsSetup],
    ["Exceptions", report.summary.exceptions],
    ["Average inspection score", report.summary.averageInspectionScore == null ? null : report.summary.averageInspectionScore / 100],
    ["Failed inspections", report.summary.failedInspections],
    ["Critical failures", report.summary.criticalFailures],
    ["Overdue", report.summary.overdue],
    ["Waived", report.summary.waived],
    ["Needs review", report.summary.needsReview],
    ["Upcoming", report.summary.upcoming],
  ]);
  summary.getCell("B18").numFmt = "0.0%";
  summary.getColumn(1).width = 28;
  summary.getColumn(2).width = 42;

  const records = book.addWorksheet("Records");
  records.columns = [
    { header: "Service Date", key: "date", width: 16 },
    { header: "Facility", key: "facility", width: 24 },
    { header: "Department", key: "department", width: 20 },
    { header: "Template", key: "template", width: 28 },
    { header: "Template Version", key: "version", width: 18 },
    { header: "Location", key: "location", width: 24 },
    { header: "Asset", key: "asset", width: 16 },
    { header: "Schedule / Window", key: "window", width: 18 },
    { header: "Occurrence State", key: "status", width: 28 },
    { header: "Recorded By", key: "by", width: 20 },
    { header: "Recorded At", key: "at", width: 24 },
    { header: "Value", key: "value", width: 14 },
    { header: "Out Of Standard", key: "oos", width: 18 },
    { header: "Corrective Action", key: "ca", width: 32 },
    { header: "Follow-Up", key: "follow", width: 18 },
    { header: "Corrected", key: "corrected", width: 14 },
    { header: "Inspection Score", key: "score", width: 18 },
    { header: "Inspection Outcome", key: "outcome", width: 22 },
    { header: "Critical Failures", key: "critical", width: 18 },
    { header: "Issue", key: "issue", width: 24 },
  ];
  for (const row of report.records) {
    const slot = row.slot;
    const numeric = slot.record?.valueNumber;
    records.addRow({
      date: slot.serviceDate,
      facility: report.metadata.facilityName,
      department: report.metadata.departmentName,
      template: slot.definitionLabel,
      version: slot.record?.templateVersion ?? slot.catalogVersion,
      location: slot.placeLabel ?? "",
      asset: slot.assetId ?? "",
      window: slot.windowStartLocal ?? slot.cycleStableKey ?? "",
      status: row.statusLabel,
      by: slot.record?.recordedByLabel ?? "",
      at: slot.record?.recordedAt ? new Date(slot.record.recordedAt) : null,
      value: numeric ?? slot.record?.valueText ?? "",
      oos: slot.record ? slot.record.outOfStandard : "",
      ca: slot.record?.correctiveActionText ?? "",
      follow: slot.followUps.map((item) => item.valueNumber ?? "Recorded").join(", "),
      corrected: row.corrected,
      score: slot.inspection?.percentage == null ? null : slot.inspection.percentage / 100,
      outcome: slot.inspection?.outcome ?? "",
      critical: slot.inspection?.criticalFailureCount ?? "",
      issue: row.issueLabel ?? "",
    });
  }
  records.getColumn("score").numFmt = "0.0%";
  records.getColumn("at").numFmt = "yyyy-mm-dd hh:mm";
  records.views = [{ state: "frozen", ySplit: 1 }];
  records.autoFilter = { from: "A1", to: "T1" };

  if (report.responses.length > 0) {
    const responses = book.addWorksheet("Responses");
    responses.columns = [
      { header: "Record ID", key: "recordId", width: 18 },
      { header: "Service Date", key: "serviceDate", width: 16 },
      { header: "Location", key: "location", width: 24 },
      { header: "Section", key: "section", width: 20 },
      { header: "Field", key: "field", width: 36 },
      { header: "Response", key: "response", width: 20 },
      { header: "Unit", key: "unit", width: 10 },
      { header: "N/A", key: "na", width: 10 },
      { header: "Out Of Standard", key: "oos", width: 16 },
      { header: "Score Weight", key: "weight", width: 14 },
      { header: "Earned", key: "earned", width: 12 },
      { header: "Critical", key: "critical", width: 12 },
      { header: "Group", key: "group", width: 24 },
      { header: "Row", key: "row", width: 16 },
    ];
    for (const row of report.responses) {
      const added = responses.addRow(row);
      if (row.scoreWeight != null) added.getCell("weight").value = row.scoreWeight;
      if (row.earned != null) added.getCell("earned").value = row.earned;
      const numeric = Number(row.response);
      if (row.response !== "" && Number.isFinite(numeric) && row.section === "" && !row.response.includes("°")) {
        added.getCell("response").value = numeric;
      }
    }
    responses.views = [{ state: "frozen", ySplit: 1 }];
    responses.autoFilter = { from: "A1", to: "N1" };
  }

  if (report.exceptions.length > 0) {
    const exceptions = book.addWorksheet("Exceptions");
    exceptions.columns = [
      { header: "Service Date", key: "date", width: 16 },
      { header: "Location", key: "location", width: 24 },
      { header: "Template", key: "template", width: 28 },
      { header: "Value", key: "value", width: 14 },
      { header: "Corrective Action", key: "ca", width: 36 },
      { header: "Follow-Up", key: "follow", width: 18 },
      { header: "Corrected", key: "corrected", width: 14 },
    ];
    for (const row of report.exceptions) {
      exceptions.addRow({
        date: row.slot.serviceDate,
        location: row.slot.placeLabel ?? "",
        template: row.slot.definitionLabel,
        value: row.slot.record?.valueNumber ?? row.slot.record?.valueText ?? "",
        ca: row.slot.record?.correctiveActionText ?? "",
        follow: row.slot.followUps.map((item) => item.valueNumber ?? "Recorded").join(", "),
        corrected: row.corrected,
      });
    }
    exceptions.views = [{ state: "frozen", ySplit: 1 }];
  }

  const bytes = await book.xlsx.writeBuffer();
  return Buffer.from(bytes);
}
